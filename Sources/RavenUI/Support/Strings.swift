/// The English text table, loaded at runtime from the bundled strings.en.json.
public final class Strings: @unchecked Sendable {
    public static let shared: Strings = {
        guard let data = RavenResources.data("strings.en", "json"), let table = try? Strings(json: data) else {
            assertionFailure("strings.en.json is missing from the resource bundle")
            return Strings(texts: [:], lists: [:])
        }
        return table
    }()

    public let texts: [String: String]
    public let lists: [String: [String]]

    public init(texts: [String: String], lists: [String: [String]]) {
        self.texts = texts
        self.lists = lists
    }

    public convenience init(json: Data) throws {
        let object = try JSONSerialization.jsonObject(with: json)
        // Not a RavenError: building one reads this very table.
        guard let dict = object as? [String: Any] else { throw CocoaError(.fileReadCorruptFile) }
        var texts: [String: String] = [:]
        var lists: [String: [String]] = [:]
        for (key, value) in dict where !key.hasPrefix("_") {
            if let s = value as? String { texts[key] = s }
            if let a = value as? [String] { lists[key] = a }
        }
        self.init(texts: texts, lists: lists)
    }

    public func has(_ key: String) -> Bool { texts[key] != nil || lists[key] != nil }

    public func text(_ key: Str, _ args: [String: String] = [:]) -> String {
        Strings.fill(texts[key.rawValue] ?? key.rawValue, args)
    }

    public func options(_ key: Str) -> [String] { lists[key.rawValue] ?? [] }

    /// Replaces `{name}`-style placeholders. Unknown placeholders are left as they are.
    public static func fill(_ template: String, _ args: [String: String]) -> String {
        guard !args.isEmpty, template.contains("{") else { return template }
        var out = template
        for (key, value) in args {
            out = out.replacingOccurrences(of: "{\(key)}", with: value)
        }
        return out
    }

    /// Placeholder names used by a template, e.g. ["name", "time"].
    public static func placeholders(in template: String) -> [String] {
        var names: [String] = []
        var current: String?
        for ch in template {
            if ch == "{" { current = "" } else if ch == "}" {
                if let c = current, !c.isEmpty { names.append(c) }
                current = nil
            } else if current != nil { current!.append(ch) }
        }
        return names
    }
}

/// Shorthand used by every view: `tr(.welcomeTitle)`, `tr(.homeInTouch, ["when": when])`.
public func tr(_ key: Str, _ args: [String: String] = [:]) -> String { Strings.shared.text(key, args) }
